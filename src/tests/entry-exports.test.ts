function readExportNames(entries: readonly string[]): Record<string, string[]> {
  const files = entries.map((entry) => resolve(ROOT, entry));
  const parsed = ts.getParsedCommandLineOfConfigFile(
    resolve(ROOT, 'tsconfig.json'),
    {},
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} },
  );
  if (parsed === undefined) throw new Error('tsconfig.json did not parse');
  const program = ts.createProgram(files, parsed.options);
  const checker = program.getTypeChecker();
  const names: Record<string, string[]> = {};
  for (const [index, file] of files.entries()) {
    const sourceFile = program.getSourceFile(file);
    if (sourceFile === undefined) throw new Error(`not in program: ${file}`);
    const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
    if (moduleSymbol === undefined) throw new Error(`not a module: ${file}`);
    names[entries[index]!] = checker
      .getExportsOfModule(moduleSymbol)
      .map((symbol) => symbol.name)
      .sort();
  }
  return names;
}

describe('entry barrel exports', () => {
  const live = readExportNames(Object.keys(PINNED));

  for (const [entry, pinned] of Object.entries(PINNED)) {
    test(`${entry} exports the pinned names`, () => {
      expect(pinned.length).toBeGreaterThan(0);
      expect(live[entry]).toEqual([...pinned].sort());
    });
  }
});
