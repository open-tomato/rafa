/**
 * Derives `.github/CODEOWNERS` from each manifest's `openTomato.team`.
 *
 * One source of truth: ownership is declared next to the code it owns, in
 * the project's own `package.json`, not in a separate file that drifts.
 * The manifests read are the root's and every workspace member's
 * ({@link MANIFEST_PATTERNS}). GitHub applies the LAST matching rule, so
 * rules are emitted shallowest first and the most specific path wins; the
 * root's rule is `/ <team>`, so `src/` and `scripts/` have an owner too.
 *
 * Usage, from the repository root:
 *
 *   bun run codeowners [--check] [--root <dir>]
 *
 * Without `--check` it writes the file. With `--check` it exits 1 when the
 * file is missing or differs from the rendering of the manifests.
 *
 * Blind spot: `--check` only confirms the file matches the manifests'
 * `openTomato.team` values byte for byte. It does NOT confirm those teams
 * exist on GitHub or have write access on the repository: a mistyped or
 * deleted team passes `--check` clean and only surfaces later through
 * `gh api repos/<org>/<repo>/codeowners/errors`, or silently when a review
 * is assigned.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** The file this script writes, relative to the root. */
export const CODEOWNERS_FILE = '.github/CODEOWNERS';

/**
 * The manifests that may declare an owner, relative to the root: the root
 * manifest and each member under the one `workspaces` glob, `packages/*`.
 */
export const MANIFEST_PATTERNS: readonly string[] = ['package.json', 'packages/*/package.json'];

/** One project and the team that owns it. */
export interface OwnedProject {
  /** The project's directory relative to the root, `/` between segments; `''` for the root. */
  relDir: string;
  /** The owning team, as GitHub spells it (`@org/team`). */
  team: string;
}

const HEADER = [
  '# GENERATED by `bun run codeowners` — do not edit by hand.',
  '# Ownership is declared per project in package.json under `openTomato.team`.',
  '',
].join('\n');

/** The path segments of a project directory; the root has none. */
function depthOf(relDir: string): number {
  return relDir === ''
    ? 0
    : relDir.split('/').length;
}

/** The CODEOWNERS path of a project directory: `/` for the root. */
function ruleOf(project: OwnedProject): string {
  return project.relDir === ''
    ? `/ ${project.team}`
    : `/${project.relDir}/ ${project.team}`;
}

/**
 * Renders the CODEOWNERS text: the generated header, then one rule per
 * project, shallowest first and by path within a depth.
 *
 * @param projects - The owned projects, in any order.
 * @returns The file's text, ending in a newline.
 */
export function renderCodeowners(projects: readonly OwnedProject[]): string {
  const rules = [...projects]
    .sort((a, b) => {
      const depth = depthOf(a.relDir) - depthOf(b.relDir);
      return depth !== 0
        ? depth
        : a.relDir.localeCompare(b.relDir);
    })
    .map(ruleOf);
  return `${HEADER}${rules.join('\n')}\n`;
}

/** The `openTomato.team` of a manifest, `null` when it declares none. */
function teamOf(manifestPath: string): string | null {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as { openTomato?: { team?: unknown } };
  const team = manifest.openTomato?.team;
  if (team === undefined || team === null) {
    return null;
  }
  if (typeof team !== 'string' || team.trim() === '') {
    throw new Error(`${manifestPath}: openTomato.team must be a non-empty string`);
  }
  return team;
}

/**
 * Reads every manifest {@link MANIFEST_PATTERNS} names under `root` and
 * keeps those that declare `openTomato.team`.
 *
 * @param root - The repository root.
 * @returns The owned projects; a manifest with no team is left out.
 * @throws When a manifest's `openTomato.team` is present but not a non-empty string.
 */
export function collectOwnedProjects(root: string): OwnedProject[] {
  return MANIFEST_PATTERNS
    .flatMap((pattern) => [...new Bun.Glob(pattern).scanSync({ cwd: root })])
    .flatMap((rel) => {
      const team = teamOf(join(root, rel));
      const relDir = rel === 'package.json'
        ? ''
        : rel.replace(/\/package\.json$/, '');
      return team === null
        ? []
        : [{ relDir, team }];
    });
}

/**
 * The command: renders the manifests under `--root` (the working directory
 * when none is given), then writes the file, or with `--check` compares it.
 *
 * @param args - The arguments after the script path.
 * @param write - Where each line goes.
 * @returns The exit code: 0 when written or up to date, 1 when missing or stale.
 */
export function main(args: readonly string[], write: (line: string) => void): number {
  const flag = args.indexOf('--root');
  const root = flag >= 0 && args[flag + 1] !== undefined
    ? args[flag + 1] as string
    : process.cwd();
  const rendered = renderCodeowners(collectOwnedProjects(root));
  const path = join(root, CODEOWNERS_FILE);
  if (!args.includes('--check')) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, rendered);
    write(`Wrote ${CODEOWNERS_FILE}.`);
    return 0;
  }
  if (!existsSync(path)) {
    write(`${CODEOWNERS_FILE} does not exist: run \`bun run codeowners\` and commit it.`);
    return 1;
  }
  if (readFileSync(path, 'utf8') !== rendered) {
    write(`${CODEOWNERS_FILE} is stale: run \`bun run codeowners\` and commit the result.`);
    return 1;
  }
  write(`${CODEOWNERS_FILE} is up to date.`);
  return 0;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2), (line) => console.log(line)));
}
